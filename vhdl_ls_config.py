# Writes vhdl_ls.toml for the VHDL LS extension, which reads it from the root of the
# folder open in VS Code. Each design becomes a library, so designs that keep their own
# copies of shared files don't clash: a Vivado project (.xpr) with the VHDL files it uses,
# or a folder with constraints (.xdc) but no project with all VHDL files below it.
# One file is written here and one in each design folder, so that opening either works.
# Without designs, a generic template is used. Files not written by this script are kept.
#
# Usage: python vhdl_ls_config.py [folder]   (default: the current folder)
import os, re, sys

MARKER = "# Generated by vhdl_ls_config.py"
# Files with these markers may be overwritten; "fpga vhdl-ls" of vivado-on-silicon-mac writes the same format
MARKERS = (MARKER, "# Generated by fpga vhdl-ls")
TEMPLATE = """# Configuration for the VHDL LS extension (https://github.com/VHDL-LS/rust_hdl).
# Lists the files of the design, so that entities and packages are found
# across files. Vivado's generated copies in deeper folders are left out.
[libraries]
design.files = [
	"*.vhd", "*.vhdl",
	"*/*.vhd", "*/*.vhdl",
	"src/**/*.vhd", "hdl/**/*.vhd", "tb/**/*.vhd",
	"*.srcs/**/*.vhd",
]
"""
# Vivado's output folders, whose copies of the sources would clash with the originals
SKIPPED = re.compile(r"^(\..+|build|xsim\.dir|.*\.(sim|runs|gen|cache|hw|ip_user_files))$", re.I)


def find_files(root):
	found = []
	for folder, dirs, files in os.walk(root):
		dirs[:] = sorted(d for d in dirs if not SKIPPED.match(d))
		found += [os.path.join(folder, f) for f in sorted(files)]
	return found


def project_files(project):
	project_dir = os.path.dirname(project)
	text = open(project, errors="ignore").read()
	files = []
	for fileset in re.finditer(r'<FileSet Name="(?:sources_1|sim_1)".*?</FileSet>', text, re.S):
		for path in re.findall(r'<File Path="([^"]+\.vhdl?)"', fileset.group(0), re.I):
			path = os.path.normpath(path.replace("$PPRDIR", project_dir))
			if os.path.exists(path) and path not in files:
				files.append(path)
	return files


def inside(path, folder):
	return os.path.normcase(path) == os.path.normcase(folder) or \
		os.path.normcase(path).startswith(os.path.normcase(folder) + os.sep)


def library_name(root, folder):
	name = re.sub(r"\W+", "_", os.path.relpath(folder, root)).strip("_").lower() or "design"
	return name if name[0].isalpha() else "lib_" + name


def toml_path(path, config_dir):
	# Forward slashes, since a backslash starts an escape in TOML strings
	return os.path.relpath(path, config_dir).replace(os.sep, "/").replace('"', '\\"')


def generated(path):
	text = open(path, errors="ignore").read()
	return any(marker in text for marker in MARKERS)


def write_config(root, config_dir, designs):
	target = os.path.join(config_dir, "vhdl_ls.toml")
	if os.path.exists(target) and not generated(target):
		print(f"{os.path.relpath(target, root)} was not generated by this script, not changing it.")
		return
	lines = [MARKER + "; run it again after adding files or designs.",
		"# Each design is a library, so work.* refers to the files of the same design.",
		"[libraries]"]
	for folder, label, files in designs:
		paths = ",\n\t".join('"%s"' % toml_path(f, config_dir) for f in files)
		lines.append(f"\n# {label}\n{library_name(root, folder)}.files = [\n\t{paths},\n]")
	with open(target, "w", newline="\n") as out:
		out.write("\n".join(lines) + "\n")
	print("Wrote " + os.path.relpath(target, root))


def main():
	root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
	found = find_files(root)
	vhdl = [f for f in found if f.lower().endswith((".vhd", ".vhdl"))]
	projects = sorted(f for f in found if f.lower().endswith(".xpr"))
	constraints = [f for f in found if f.lower().endswith(".xdc")]

	if not projects and not constraints:
		target = os.path.join(root, "vhdl_ls.toml")
		if os.path.exists(target) and not generated(target):
			print("vhdl_ls.toml was not generated by this script, not changing it.")
			return
		with open(target, "w", newline="\n") as out:
			out.write(MARKER + "\n" + TEMPLATE)
		print("Wrote vhdl_ls.toml")
		return

	# (design folder, label, files)
	designs = []
	project_dirs = []
	for project in projects:
		project_dirs.append(os.path.dirname(project))
		designs.append((os.path.dirname(project), os.path.basename(project), project_files(project)))
	for folder in sorted({os.path.dirname(f) for f in constraints}):
		if not any(inside(folder, d) for d in project_dirs) and not any(d == folder for d, _, _ in designs):
			designs.append((folder, "VHDL files below " + (os.path.relpath(folder, root) or "."),
				sorted(f for f in vhdl if inside(f, folder))))

	# Folders with constraints but no VHDL (e.g. Verilog example designs of IP cores) are skipped
	designs = [design for design in designs if design[2]]
	write_config(root, root, designs)
	for design in designs:
		if design[0] != root:
			write_config(root, design[0], [design])


if __name__ == "__main__":
	main()
